-- 동적 테이블이 없는 환경 전용: CORE.CUSTOMER_QUALITY_EVENT를 표준화 결과 CSV로 직접 적재한다.

-- 대상 DB 확인: SL_QDW_DEMO·SL_QDW_DEV가 아니면 예외로 중단한다(snow sql은 첫 오류에서 멈춘다).
EXECUTE IMMEDIATE $$
DECLARE
  not_demo_db EXCEPTION (-20001, 'ABORT: demo data loads only into SL_QDW_DEMO or SL_QDW_DEV');
BEGIN
  IF (CURRENT_DATABASE() IS NULL OR CURRENT_DATABASE() NOT IN ('SL_QDW_DEMO', 'SL_QDW_DEV')) THEN
    RAISE not_demo_db;
  END IF;
  RETURN 'OK: ' || CURRENT_DATABASE();
END;
$$;

CREATE FILE FORMAT IF NOT EXISTS RAW.DEMO_CSV TYPE = CSV PARSE_HEADER = TRUE FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('') EMPTY_FIELD_AS_NULL = TRUE TIMESTAMP_FORMAT = AUTO DATE_FORMAT = AUTO ENCODING = 'UTF8';
CREATE STAGE IF NOT EXISTS RAW.DEMO_STAGE FILE_FORMAT = RAW.DEMO_CSV;

PUT 'file://<% demo_dir %>/CORE.CUSTOMER_QUALITY_EVENT.csv' @RAW.DEMO_STAGE/CORE.CUSTOMER_QUALITY_EVENT/ OVERWRITE = TRUE AUTO_COMPRESS = TRUE;

TRUNCATE TABLE IF EXISTS CORE.CUSTOMER_QUALITY_EVENT;
COPY INTO CORE.CUSTOMER_QUALITY_EVENT FROM @RAW.DEMO_STAGE/CORE.CUSTOMER_QUALITY_EVENT/ FILE_FORMAT = (FORMAT_NAME = RAW.DEMO_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = ABORT_STATEMENT;
